package diskgc

import "golang.org/x/sys/unix"

// HostFS is the FS of the host atelet runs on.
type HostFS struct{}

func (HostFS) Device(dir string) (uint64, error) {
	var st unix.Stat_t
	if err := unix.Stat(dir, &st); err != nil {
		return 0, err
	}
	return uint64(st.Dev), nil //nolint:unconvert // Dev is int32 on darwin
}

func (HostFS) Space(dir string) (total, avail uint64, err error) {
	var st unix.Statfs_t
	if err := unix.Statfs(dir, &st); err != nil {
		return 0, 0, err
	}
	return st.Blocks * uint64(st.Bsize), st.Bavail * uint64(st.Bsize), nil
}
